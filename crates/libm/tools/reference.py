#!/usr/bin/env python3
"""Write tests/reference.rs: asinh and acosh at sample arguments, computed to
60 significant digits with Python's decimal module and rounded once to the
nearest f64. Run from the crate directory: python3 tools/reference.py"""
import random
import struct
from decimal import Decimal, getcontext

getcontext().prec = 60


def asinh(x: Decimal) -> Decimal:
    a = abs(x)
    if a < Decimal('1e-3'):
        # The closed form cancels for tiny a; the series' next term is below
        # a^9/10, far under one f64 ulp here.
        a2 = a * a
        y = a * (1 - a2 / 6 + 3 * a2 * a2 / 40 - 15 * a2 * a2 * a2 / 336)
    else:
        y = (a + (a * a + 1).sqrt()).ln()
    return y if x >= 0 else -y


def acosh(x: Decimal) -> Decimal:
    return (x + (x * x - 1).sqrt()).ln()


def bits(f: float) -> str:
    return '0x%016x' % struct.unpack('<Q', struct.pack('<d', f))[0]


random.seed(20261018)
asinh_args = [1e-300, 1e-20, 1.4901161193847656e-08, 1e-8, 1e-5, 0.001, 0.1, 0.5, 0.75, 1.0, 1.5,
              1.9999999999999998, 2.0, 2.5, 10.0, 100.0, 1e6, 67108863.99999999, 67108864.0, 1e10, 1e100, 1e300]
asinh_args += [10 ** random.uniform(-12, 12) for _ in range(400)]
asinh_args += [-a for a in asinh_args[::7]]
acosh_args = [1.0, 1.0000000000000002, 1.000001, 1.001, 1.1, 1.5, 1.9999999999999998, 2.0, 3.0, 10.0,
              1e6, 67108863.99999999, 67108864.0, 1e10, 1e100, 1e300]
acosh_args += [1 + 10 ** random.uniform(-12, 1) for _ in range(200)]
acosh_args += [10 ** random.uniform(1, 15) for _ in range(200)]

out = ['// @generated by tools/reference.py; do not edit.', '',
       '//! (argument bits, result bits), the result computed to 60 digits and',
       '//! rounded once to f64.', '',
       'pub const ASINH: &[(u64, u64)] = &[']
for a in asinh_args:
    out.append(f'    ({bits(a)}, {bits(float(asinh(Decimal(a))))}),')
out += ['];', '', 'pub const ACOSH: &[(u64, u64)] = &[']
for a in acosh_args:
    out.append(f'    ({bits(a)}, {bits(float(acosh(Decimal(a))))}),')
out += ['];', '']
open('tests/reference.rs', 'w').write('\n'.join(out))
print(f'{len(asinh_args)} asinh and {len(acosh_args)} acosh references')
