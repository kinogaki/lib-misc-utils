#!/usr/bin/env python3
"""Write src/tables.rs from the Unicode Character Database files in ucd/.

    python3 tools/generate.py          # from the crate directory

Inputs (Unicode 17.0.0, https://www.unicode.org/Public/17.0.0/ucd/):
  GraphemeBreakProperty.txt  Grapheme_Cluster_Break
  emoji-data.txt             Extended_Pictographic
  DerivedCoreProperties.txt  Indic_Conjunct_Break (InCB)
  WordBreakProperty.txt      Word_Break
  DerivedGeneralCategory.txt General_Category (for the combining marks)

Output: sorted, merged code point ranges with their values. Code points in no
range have the default value (Other / not pictographic / no InCB / not a mark).
tests/tables.rs checks every code point against these files, and
tests/conformance.rs runs the UCD's GraphemeBreakTest.txt and WordBreakTest.txt.
"""
import re
from pathlib import Path

UCD = Path('ucd')
VERSION = (17, 0, 0)

GRAPHEME = ['Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ', 'Regional_Indicator', 'Prepend',
            'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT']
INCB = ['None', 'Consonant', 'Extend', 'Linker']
WORD = ['Other', 'CR', 'LF', 'Newline', 'Extend', 'ZWJ', 'Regional_Indicator', 'Format', 'Katakana',
        'Hebrew_Letter', 'ALetter', 'Single_Quote', 'Double_Quote', 'MidNumLet', 'MidLetter', 'MidNum',
        'Numeric', 'ExtendNumLet', 'WSegSpace']


def ranges(path: Path, field: int = 1, keep=None):
    """(first, last, value) for each data line; `keep(fields)` filters."""
    for line in path.read_text(encoding='utf-8').splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(';')]
        if keep is not None and not keep(fields):
            continue
        first, _, last = fields[0].partition('..')
        yield int(first, 16), int(last or first, 16), fields[field]


def merged(values: dict[int, int]):
    """Runs of consecutive code points with equal values."""
    out = []
    for cp in sorted(values):
        v = values[cp]
        if out and out[-1][1] == cp - 1 and out[-1][2] == v:
            out[-1][1] = cp
        else:
            out.append([cp, cp, v])
    return out


def main():
    grapheme: dict[int, int] = {}
    for a, b, v in ranges(UCD / 'GraphemeBreakProperty.txt'):
        for cp in range(a, b + 1):
            grapheme[cp] = GRAPHEME.index(v)
    for a, b, _ in ranges(UCD / 'emoji-data.txt', keep=lambda f: f[1] == 'Extended_Pictographic'):
        for cp in range(a, b + 1):
            grapheme[cp] = grapheme.get(cp, 0) | 1 << 4
    for a, b, v in ranges(UCD / 'DerivedCoreProperties.txt', field=2, keep=lambda f: f[1] == 'InCB'):
        for cp in range(a, b + 1):
            grapheme[cp] = grapheme.get(cp, 0) | INCB.index(v) << 5
    word: dict[int, int] = {}
    for a, b, v in ranges(UCD / 'WordBreakProperty.txt'):
        for cp in range(a, b + 1):
            word[cp] = WORD.index(v)
    marks: dict[int, int] = {}
    for a, b, v in ranges(UCD / 'DerivedGeneralCategory.txt', keep=lambda f: f[1] in ('Mn', 'Mc', 'Me')):
        for cp in range(a, b + 1):
            marks[cp] = 1

    def table(name, kind, rows, value=True):
        body = ''.join(f'    (0x{a:x}, 0x{b:x}, {v}),\n' if value else f'    (0x{a:x}, 0x{b:x}),\n'
                       for a, b, v in rows)
        return f'#[rustfmt::skip]\npub(crate) static {name}: &[{kind}] = &[\n{body}];\n'

    def ascii(name, values):
        row = ', '.join(str(values.get(cp, 0)) for cp in range(128))
        return f'#[rustfmt::skip]\npub(crate) static {name}: [u8; 128] = [{row}];\n'

    out = [
        '// @generated by tools/generate.py from the Unicode Character Database in ucd/; do not edit.',
        '',
        '//! Sorted, non-overlapping inclusive code point ranges; code points in no range',
        '//! have the default value.',
        '',
        f'/// The Unicode version of the tables.',
        f'pub const UNICODE_VERSION: (u8, u8, u8) = {VERSION};',
        '',
        '/// Grapheme properties: bits 0-3 the Grapheme_Cluster_Break value (the index in',
        '/// `grapheme::Break`), bit 4 Extended_Pictographic, bits 5-6 Indic_Conjunct_Break',
        '/// (the index in `grapheme::Conjunct`).',
        table('GRAPHEME', '(u32, u32, u8)', merged(grapheme)),
        '/// [`GRAPHEME`] for the ASCII code points.',
        ascii('GRAPHEME_ASCII', grapheme),
        '/// Word_Break values (the index in `word::Break`).',
        table('WORD', '(u32, u32, u8)', merged(word)),
        '/// [`WORD`] for the ASCII code points.',
        ascii('WORD_ASCII', word),
        '/// Combining marks: General_Category Mn, Mc or Me.',
        table('MARKS', '(u32, u32)', merged(marks), value=False),
    ]
    Path('src/tables.rs').write_text('\n'.join(out))
    print(f'grapheme {len(merged(grapheme))}, word {len(merged(word))}, mark {len(merged(marks))} ranges')


if __name__ == '__main__':
    main()
