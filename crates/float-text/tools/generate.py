#!/usr/bin/env python3
"""Write src/tables.rs: the powers of ten of the shortest-digits search
(src/shortest.rs), as 126-bit values split into (high, low) 63-bit words.

    python3 tools/generate.py          # from the crate directory

For e in -292..=324, with 10^e = beta * 2^r and 2^125 <= beta < 2^126:
    G[e + 292] = floor(beta) + 1
tests/tables.rs checks the definition with exact integer arithmetic.
"""
from pathlib import Path

E_MIN, E_MAX = -292, 324


def flog2pow10(e: int) -> int:
    """floor(e * log2(10)), exact for |e| <= 1233 (as the Rust code computes it)."""
    return (e * 913_124_641_741) >> 38


rows = []
for e in range(E_MIN, E_MAX + 1):
    r = flog2pow10(e) - 125
    num = 10 ** max(e, 0) * 2 ** max(-r, 0)
    den = 10 ** max(-e, 0) * 2 ** max(r, 0)
    beta = num // den
    assert 2 ** 125 <= beta < 2 ** 126, e
    g = beta + 1
    rows.append((g >> 63, g & (2 ** 63 - 1)))
out = ['//! Generated by tools/generate.py; do not edit.', '',
       '/// The smallest exponent of ten in [`G`].',
       f'pub(crate) const G_MIN: i32 = {E_MIN};', '',
       '/// `floor(10^e / 2^r) + 1` in [2^125, 2^126] for e in -292..=324 (index e + 292),',
       '/// as (high 63 bits, low 63 bits).',
       '#[rustfmt::skip]', f'pub(crate) static G: [(u64, u64); {len(rows)}] = [']
out += [f'    (0x{a:016x}, 0x{b:016x}),' for a, b in rows]
out += ['];', '']
Path('src/tables.rs').write_text('\n'.join(out))
print(f'{len(rows)} entries')
