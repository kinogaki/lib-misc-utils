#!/usr/bin/env python3
"""Write src/tables.rs: the powers of ten of the shortest-digits search
(src/shortest.rs), as 128-bit significands split into (high, low) words.

    python3 tools/generate.py          # from the crate directory

For e in -293..=323 (the exponents 10^-(k+1) the search scales by):
    POW10[e + 293] = floor(10^e * 2^(127 - floor(log2 10^e)))   in [2^127, 2^128)
tests/tables.rs checks the definition with exact integer arithmetic.
"""
from pathlib import Path

E_MIN, E_MAX = -293, 323


def floor_log2_pow10(e: int) -> int:
    """floor(log2(10^e)) exactly."""
    if e >= 0:
        return (10 ** e).bit_length() - 1
    # 10^e = 1 / 10^-e: floor(log2) = -ceil(log2(10^-e)).
    d = 10 ** -e
    b = d.bit_length() - 1
    return -b if d == 1 << b else -(b + 1)


rows = []
for e in range(E_MIN, E_MAX + 1):
    b = floor_log2_pow10(e)
    shift = 127 - b
    if e >= 0:
        num, den = 10 ** e, 1
    else:
        num, den = 1, 10 ** -e
    t = (num << shift) // den if shift >= 0 else num // (den << -shift)
    assert 2 ** 127 <= t < 2 ** 128, e
    rows.append((t >> 64, t & (2 ** 64 - 1)))
out = ['//! Generated by tools/generate.py; do not edit.', '',
       '/// The smallest power of ten in [`POW10`].',
       f'pub(crate) const POW10_MIN: i32 = {E_MIN};', '',
       '/// `floor(10^e × 2^(127 - floor(log2 10^e)))` for e in -293..=323 (index',
       '/// e + 293): the 128-bit significand of 10^e, as (high, low) words.',
       '#[rustfmt::skip]', f'pub(crate) static POW10: [(u64, u64); {len(rows)}] = [']
out += [f'    (0x{a:016x}, 0x{c:016x}),' for a, c in rows]
out += ['];', '']
Path('src/tables.rs').write_text('\n'.join(out))
print(f'{len(rows)} entries')
